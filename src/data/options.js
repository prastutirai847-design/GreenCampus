export function getCategoryLabel(category) {
  return CATEGORY_META[category]?.label ?? category;
}

export function getFuelType(id) {
  return FUEL_TYPES.find((item) => item.id === id);
}

export function isRefrigerantFuel(id) {
  return getFuelType(id)?.kind === 'refrigerant';
}

export function getWasteCategory(id) {
  return WASTE_CATEGORIES.find((item) => item.id === id);
}

export function getDisposalMethod(id) {
  return DISPOSAL_METHODS.find((item) => item.id === id);
}

export function getCommuteMode(id) {
  return COMMUTE_MODES.find((item) => item.id === id);
}
